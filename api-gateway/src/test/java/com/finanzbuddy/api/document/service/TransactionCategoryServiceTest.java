package com.finanzbuddy.api.document.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import com.finanzbuddy.api.document.dto.TransactionResponse;
import com.finanzbuddy.api.document.dto.TransactionVersionResponse;
import com.finanzbuddy.api.entity.User;
import com.finanzbuddy.api.repository.TransactionCategoryRepository;
import com.finanzbuddy.api.repository.TransactionCategoryRepository.TransactionSnapshot;
import com.finanzbuddy.api.repository.UserRepository;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.web.server.ResponseStatusException;

class TransactionCategoryServiceTest {

    private EmbeddedDatabase database;
    private JdbcTemplate jdbcTemplate;
    private TransactionCategoryRepository categoryRepository;
    private UserRepository userRepository;
    private TransactionCategoryService service;

    @BeforeEach
    void setUp() {
        database =
                new EmbeddedDatabaseBuilder()
                        .setName("category-test-" + UUID.randomUUID())
                        .setType(EmbeddedDatabaseType.H2)
                        .build();
        jdbcTemplate = new JdbcTemplate(database);
        jdbcTemplate.execute(
                "CREATE TABLE documents (id BIGINT PRIMARY KEY, user_id BIGINT, status VARCHAR(20))");
        jdbcTemplate.execute(
                "CREATE TABLE transactions (id BIGINT PRIMARY KEY, document_id BIGINT, user_id"
                        + " BIGINT, booking_date DATE, value_date DATE, amount DECIMAL(19,4),"
                        + " currency VARCHAR(3), counterparty VARCHAR(500), description CLOB,"
                        + " category VARCHAR(255))");
        jdbcTemplate.execute(
                "CREATE TABLE personal_transaction_categories (id BIGINT GENERATED BY DEFAULT AS IDENTITY"
                        + " PRIMARY KEY, user_id BIGINT NOT NULL, name VARCHAR(255) NOT NULL,"
                        + " normalized_name VARCHAR(255) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP"
                        + " NOT NULL, UNIQUE (user_id, normalized_name))");
        jdbcTemplate.execute(
                "CREATE TABLE transaction_versions (id BIGINT GENERATED BY DEFAULT AS IDENTITY"
                        + " PRIMARY KEY, transaction_id BIGINT NOT NULL, document_id BIGINT NOT NULL,"
                        + " user_id BIGINT NOT NULL, version_number INT NOT NULL, booking_date DATE,"
                        + " value_date DATE, amount DECIMAL(19,4), currency VARCHAR(3),"
                        + " counterparty VARCHAR(500), description CLOB, category VARCHAR(255)"
                        + " CHECK (category IS NULL OR category <> 'Broken'),"
                        + " created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,"
                        + " UNIQUE (transaction_id, user_id, version_number))");
        jdbcTemplate.update("INSERT INTO documents VALUES (1, 7, 'PROCESSED')");
        insertTransaction(101, "Parsed");
        insertTransaction(102, "Food");

        categoryRepository = new TransactionCategoryRepository(jdbcTemplate);
        userRepository = mock(UserRepository.class);
        User user = new User();
        user.setId(7L);
        user.setEmail("owner@example.com");
        when(userRepository.findByEmail("owner@example.com")).thenReturn(Optional.of(user));
        service =
                new TransactionCategoryService(
                        userRepository,
                        categoryRepository,
                        new DataSourceTransactionManager(database));
    }

    @AfterEach
    void tearDown() {
        database.shutdown();
    }

    @Test
    void materializesInitialSnapshotAndAppendsEveryLaterCategoryEdit() {
        TransactionResponse first = service.updateCategory("owner@example.com", 101, "Housing");
        TransactionResponse second = service.updateCategory("owner@example.com", 101, "Bills");

        assertThat(first.category()).isEqualTo("Housing");
        assertThat(second.category()).isEqualTo("Bills");
        assertThat(service.getVersions("owner@example.com", 101))
                .extracting(TransactionVersionResponse::versionNumber)
                .containsExactly(1, 2, 3);
        assertThat(service.getVersions("owner@example.com", 101))
                .extracting(version -> version.transaction().category())
                .containsExactly("Parsed", "Housing", "Bills");
    }

    @Test
    void rejectsBlankCategoriesAndKeepsPersonalNamesUniqueIgnoringCase() {
        assertThatThrownBy(() -> service.updateCategory("owner@example.com", 101, "  "))
                .isInstanceOf(ResponseStatusException.class)
                .extracting(exception -> ((ResponseStatusException) exception).getStatusCode())
                .isEqualTo(HttpStatus.BAD_REQUEST);

        service.createCategoryAndAssign("owner@example.com", 101, "Travel");
        var duplicate = service.createCategoryAndAssign("owner@example.com", 102, " travel ");

        assertThat(duplicate.name()).isEqualTo("Travel");
        assertThat(duplicate.transaction().category()).isEqualTo("Travel");
        assertThat(
                        jdbcTemplate.queryForObject(
                                "SELECT COUNT(*) FROM personal_transaction_categories"
                                        + " WHERE user_id = 7",
                                Integer.class))
                .isEqualTo(1);
    }

    @Test
    void rollsBackBaselineAndPersonalCategoryWhenSnapshotAppendFails() {
        assertThatThrownBy(
                        () -> service.createCategoryAndAssign("owner@example.com", 101, "Broken"))
                .isInstanceOf(ResponseStatusException.class)
                .extracting(exception -> ((ResponseStatusException) exception).getStatusCode())
                .isEqualTo(HttpStatus.CONFLICT);

        assertThat(count("transaction_versions")).isZero();
        assertThat(count("personal_transaction_categories")).isZero();
    }

    @Test
    void reportsConcurrentVersionConstraintViolationAsConflict() {
        TransactionCategoryRepository racingRepository = mock(TransactionCategoryRepository.class);
        TransactionResponse current = transaction(101, "Parsed");
        when(racingRepository.findOwnedTransaction(7L, 101L))
                .thenReturn(new TransactionSnapshot(101, 1, 7, current));
        when(racingRepository.findVersions(7L, 101L))
                .thenReturn(List.of(new TransactionVersionResponse(1, current, null)));
        org.mockito.Mockito.doThrow(new DuplicateKeyException("version already exists"))
                .when(racingRepository)
                .appendVersion(7L, 1L, 2, transaction(101, "Changed"));
        TransactionCategoryService racingService =
                new TransactionCategoryService(
                        userRepository,
                        racingRepository,
                        new DataSourceTransactionManager(database));

        assertThatThrownBy(() -> racingService.updateCategory("owner@example.com", 101, "Changed"))
                .isInstanceOf(ResponseStatusException.class)
                .extracting(exception -> ((ResponseStatusException) exception).getStatusCode())
                .isEqualTo(HttpStatus.CONFLICT);
    }

    private void insertTransaction(long id, String category) {
        jdbcTemplate.update(
                "INSERT INTO transactions VALUES (?, 1, 7, DATE '2024-01-01',"
                        + " DATE '2024-01-02', 12.50, 'EUR', 'Counterparty', 'Description', ?)",
                id,
                category);
    }

    private static TransactionResponse transaction(long id, String category) {
        return new TransactionResponse(
                id,
                LocalDate.parse("2024-01-01"),
                LocalDate.parse("2024-01-02"),
                new BigDecimal("12.50"),
                "EUR",
                "Counterparty",
                "Description",
                category);
    }

    private int count(String table) {
        return jdbcTemplate.queryForObject("SELECT COUNT(*) FROM " + table, Integer.class);
    }
}
